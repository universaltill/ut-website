#!/usr/bin/env node
// Generates the locale-dependent files of the website from the published
// list (ADR-0177 section 4, ut-docs#5406), so no locale is named by hand:
//
//   site/i18n-data.js                 the dictionaries i18n.js runs on
//   site/staticwebapp.config.json     locale routes + withdrawn 301s; every
//                                     non-locale entry is kept untouched
//
//   node scripts/gen-locales.mjs           write both files
//   node scripts/gen-locales.mjs --check   exit 1 if either is stale (CI)
//
// It also refuses to generate when the inputs are unsafe or inconsistent:
// a string file for a locale the list does not publish, a key that is not in
// en.json, an empty value, a `core` key missing from a published non-English
// locale, or an HTML-bearing value outside the allow-list (a, b, i, em,
// strong, br, span, code; no handlers, no script URLs; tag set and link
// targets equal to the English text).
import fs from "node:fs";
import path from "node:path";
import { ROOT, SOURCE, buildSwaConfig, htmlProblems, i18nDir, loadDicts, loadStrings, myLocales, serializeSwa } from "./lib/locales.mjs";

export function validate({ list, english, meta, locales }, dir) {
  const errors = [];
  const published = new Set(locales.map((l) => l.url));
  for (const f of fs.readdirSync(dir)) {
    const m = f.match(/^([a-z]{2}-[a-z]{2})\.json$/);
    if (m && !published.has(m[1]) && m[1] !== SOURCE) errors.push(`${f}: strings for a locale the published list does not serve (website surface)`);
  }
  for (const l of locales) {
    if (l.url === SOURCE) continue;
    const strings = loadStrings(l.url, dir);
    for (const [k, v] of Object.entries(strings)) {
      if (!(k in english)) errors.push(`${l.url}: ${k} is not an English key`);
      else if (typeof v !== "string" || v.trim() === "") errors.push(`${l.url}: ${k} is empty`);
      else if (meta[k] && meta[k].html === true) for (const p of htmlProblems(v, english[k])) errors.push(`${l.url}: ${k}: ${p}`);
      else if (/<\/?[a-z][^>]*>/i.test(v) && !/<\/?[a-z][^>]*>/i.test(english[k])) errors.push(`${l.url}: ${k}: markup in a plain-text value`);
    }
    for (const [k, m] of Object.entries(meta)) {
      if (m.core === true && !(k in strings)) errors.push(`${l.url}: core key ${k} is not shipped (the locale must not be published)`);
    }
  }
  return errors;
}

export function renderData({ list, locales, dicts }) {
  const body = JSON.stringify({ DEFAULT: SOURCE, my: [...myLocales(list)].sort(), locales: Object.fromEntries(locales.map((l) => [l.url, dicts[l.url]])) });
  return `// GENERATED by scripts/gen-locales.mjs from i18n/published/locales.json and i18n/*.json — do not edit.\n// The language list and every string come from the published-locale list (ADR-0177).\nwindow.UT_I18N_DATA = ${body};\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const dir = i18nDir();
  const data = loadDicts(dir);
  const errors = validate(data, dir);
  if (errors.length) { console.error(errors.map((e) => "gen-locales: " + e).join("\n")); process.exit(1); }
  const swaPath = path.join(ROOT, "site", "staticwebapp.config.json");
  const out = {
    "site/i18n-data.js": renderData(data),
    "site/staticwebapp.config.json": serializeSwa(buildSwaConfig(JSON.parse(fs.readFileSync(swaPath, "utf8")), data.list)),
  };
  let stale = 0;
  for (const [rel, text] of Object.entries(out)) {
    const p = path.join(ROOT, rel);
    const have = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
    if (check) { if (have !== text) { console.error(`gen-locales: ${rel} is out of date; run: node scripts/gen-locales.mjs`); stale++; } }
    else if (have !== text) { fs.writeFileSync(p, text); console.log(`gen-locales: wrote ${rel}`); }
  }
  if (stale) process.exit(1);
  console.log(`gen-locales: ${check ? "up to date" : "done"} (${data.locales.map((l) => l.url).join(", ")})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) main();
