#!/usr/bin/env node
// data/plan-wizard-rules.json (a byte-identical copy of ut-docs
// reference/plan-wizard-rules.json) -> site/plan-wizard-rules.js, the classic
// script site/wizard-rules.js reads (site/ is a plain static tree, no bundler).
// Never edit either file by hand (ut-docs#4962).
// `node scripts/gen-plan-wizard-rules.mjs --check` fails if the committed file is stale.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
// ut-docs plan ids -> the wizard's (same map as gen-plan-prices.mjs, plus enterprise).
const PLANS = { local: "local", local_plus: "plus", shop: "shop", pro: "pro", multi_location: "multi", enterprise: "enterprise" };
const fail = (msg) => { throw new Error("plan-wizard-rules.json: " + msg); };
const isStrList = (v) => Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === "string" && x !== "");

export function build(src) {
  if (!src || src.schema_version !== 1) fail("unknown schema_version " + (src && src.schema_version));
  if (JSON.stringify(src.plans) !== JSON.stringify(Object.keys(PLANS))) fail("plans must be exactly " + Object.keys(PLANS).join(", "));
  if (!isStrList(src.managed_fiscal_markets)) fail("managed_fiscal_markets must be a non-empty list of strings");
  if (!Array.isArray(src.plan_rules) || !src.plan_rules.length) fail("plan_rules must be a non-empty list");
  const seen = new Set();
  const rules = src.plan_rules.map((r, i) => {
    if (typeof r.id !== "string" || !/^[a-z0-9-]+$/.test(r.id)) fail(`plan_rules[${i}].id must match [a-z0-9-]+`);
    if (seen.has(r.id)) fail("duplicate rule id " + r.id);
    seen.add(r.id);
    if (!Object.prototype.hasOwnProperty.call(PLANS, r.plan)) fail(`rule ${r.id}: unknown plan ${JSON.stringify(r.plan)}`);
    if (typeof r.built !== "boolean") fail(`rule ${r.id}: built must be a boolean`);
    if (!r.if || typeof r.if !== "object" || Array.isArray(r.if) || !Object.keys(r.if).length) fail(`rule ${r.id}: if must be a non-empty object`);
    const cond = {};
    for (const [q, v] of Object.entries(r.if)) {
      if (typeof v === "string") {
        if (!isStrList(src[v])) fail(`rule ${r.id}: if.${q} names ${JSON.stringify(v)}, which is not a top-level list of strings`);
        cond[q] = src[v].slice();
      } else if (isStrList(v)) cond[q] = v.slice();
      else fail(`rule ${r.id}: if.${q} must be a non-empty list of strings or a list name`);
    }
    return { id: r.id, plan: PLANS[r.plan], if: cond, built: r.built };
  });
  return { decidedOn: src.decided_on, decisionSource: src.decision_source, managedFiscalMarkets: src.managed_fiscal_markets.slice(), rules };
}

export function render(out) {
  return "// GENERATED by scripts/gen-plan-wizard-rules.mjs from data/plan-wizard-rules.json. Do not edit.\n" +
    "(typeof window !== \"undefined\" ? window : globalThis).UT_PLAN_WIZARD_RULES = " + JSON.stringify(out) + ";\n";
}

function main() {
  const src = JSON.parse(fs.readFileSync(path.join(ROOT, "data/plan-wizard-rules.json"), "utf8"));
  const text = render(build(src));
  const file = path.join(ROOT, "site/plan-wizard-rules.js");
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
      console.error("site/plan-wizard-rules.js is stale: run node scripts/gen-plan-wizard-rules.mjs");
      process.exit(1);
    }
    console.log("OK: site/plan-wizard-rules.js matches data/plan-wizard-rules.json");
  } else fs.writeFileSync(file, text);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
