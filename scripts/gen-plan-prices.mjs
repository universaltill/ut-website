#!/usr/bin/env node
// data/plan-prices.json (a byte-identical copy of ut-docs reference/plan-prices.json,
// amounts in integer minor units) -> site/plan-prices.js, the classic script the
// wizard reads (site/ is a plain static tree, no bundler). The page gets whole
// currency units and only the fields it shows. Never edit either file by hand.
// `node scripts/gen-plan-prices.mjs --check` fails if the committed file is stale.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const src = JSON.parse(fs.readFileSync(path.join(ROOT, "data/plan-prices.json"), "utf8"));
if (src.schema_version !== 1) throw new Error("plan-prices.json: unknown schema_version " + src.schema_version);

// ut-docs country keys -> the wizard's market ids; ut-docs plan ids -> the wizard's.
const MARKETS = { gb: "uk", de: "de", eurozone: "eu" };
const PLANS = { local: "local", local_plus: "plus", shop: "shop", pro: "pro", multi_location: "multi" };
const units = (minor) => minor / 100;
const need = (v, what) => { if (v === undefined || v === null) throw new Error("plan-prices.json: missing " + what); return v; };

const markets = {};
let extraLocation = null;
for (const [docsKey, id] of Object.entries(MARKETS)) {
  const c = need(src.countries[docsKey], "countries." + docsKey);
  const m = { currency: c.currency, tsePerMainTill: 0, plans: {} };
  for (const [dk, pid] of Object.entries(PLANS)) {
    m.plans[pid] = { monthly: units(need(c.monthly_minor[dk], `${docsKey}.monthly_minor.${dk}`)), annualPerMonth: units(need(c.annual_per_month_minor[dk], `${docsKey}.annual.${dk}`)) };
  }
  const x = { monthly: units(c.extra_location.monthly_minor), maxLocations: c.extra_location.max_locations };
  if (extraLocation && JSON.stringify(extraLocation) !== JSON.stringify(x)) throw new Error("extra_location differs between markets; the wizard assumes one value");
  extraLocation = x;
  if (c.tse_per_main_till) {
    m.tsePerMainTill = units(c.tse_per_main_till.monthly_minor);
    m.tseFromPlan = PLANS[c.tse_per_main_till.applies_to.map((p) => p).sort((a, b) => Object.values(PLANS).indexOf(PLANS[a]) - Object.values(PLANS).indexOf(PLANS[b]))[0]];
    if (c.tse_per_main_till.discountable !== false) throw new Error("the TSE line must be non-discountable");
  }
  markets[id] = m;
}
const out = {
  effectiveFrom: src.effective_from,
  extraLocation,
  includedLocations: 3, // Multi-location includes three locations (subscription-plans.md)
  markets,
};
const text =
  "// GENERATED by scripts/gen-plan-prices.mjs from data/plan-prices.json. Do not edit.\n" +
  "(typeof window !== \"undefined\" ? window : globalThis).UT_PLAN_PRICES = " + JSON.stringify(out) + ";\n";
const file = path.join(ROOT, "site/plan-prices.js");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
    console.error("site/plan-prices.js is stale: run node scripts/gen-plan-prices.mjs");
    process.exit(1);
  }
  console.log("OK: site/plan-prices.js matches data/plan-prices.json");
} else fs.writeFileSync(file, text);
